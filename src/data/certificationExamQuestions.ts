function getDefaultTrapMetadata(q: CertExamQuestionItem): QuestionTrapMetadata {
  const topicMap: Record<ExamPillar, string> = {
    sql: 'SQL',
    modelisation: 'Modélisation',
    transactions: 'Transactions',
    administration: 'Administration',
  };

  const domainSub = q.domainNameFr.includes(':') 
    ? q.domainNameFr.split(':')[1].trim() 
    : q.domainNameFr;

  return {
    topic: topicMap[q.pillar] || 'SQL',
    subtopic: domainSub,
    difficulty: 3,
    trap: q.conceptId.replace(/_/g, ' '),
    concepts: [topicMap[q.pillar] || 'SQL', domainSub],
    estimatedTime: 45,
    warningMsgFr: `Attention au piège de certification sur : ${domainSub}.`,
    warningMsgEn: `Watch out for the certification trap on : ${q.domainNameEn}.`,
    antidoteRuleFr: q.explanationFr,
    antidoteRuleEn: q.explanationEn,
  };
}

export const certificationExamQuestions: CertExamQuestionItem[] = rawCertificationExamQuestions.map((q) => {
  const trapMeta = conceptTrapMetadataMap[q.conceptId] || getDefaultTrapMetadata(q);
  return {
    ...q,
    trapMetadata: trapMeta,
  };
});
